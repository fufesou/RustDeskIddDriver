inline const CtaVideoTiming* CtaShortVideoTiming(BYTE svd)
{
    // Only VICs 1 through 64 use bit 7 as the native-format flag.
    const BYTE vic = svd >= 129 && svd <= 192 ? svd & 0x7f : svd;
    const auto end = std::end(CtaProgressiveTimings);
    const auto it = std::lower_bound(std::begin(CtaProgressiveTimings), end, vic,
        [](const CtaVideoTiming& timing, BYTE code) { return timing.lastVic < code; });
    return it != end && it->firstVic <= vic ? it : nullptr;
}
